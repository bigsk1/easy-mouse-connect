"""Copy a verified preview and a sanitized source snapshot to a NEW destination."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import zipfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--package", type=Path, required=True)
parser.add_argument("--destination", type=Path, required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
version = json.loads((root / "apps/desktop/tauri.conf.json").read_text(encoding="utf-8"))["version"]
package = args.package.resolve(strict=True)
destination = args.destination.resolve()
if destination.exists() and any(destination.iterdir()):
    raise SystemExit("Destination is not empty; choose a new versioned folder.")
files = ["easy-mouse-connect.exe", f"EasyMouseConnect-{version}-preview-setup.exe", "START-HERE.txt"]
for name in files:
    if not (package / name).is_file():
        raise SystemExit(f"Missing package file: {name}")
destination.mkdir(parents=True, exist_ok=True)
for name in files:
    shutil.copy2(package / name, destination / name)

# Explicit source roots keep local configuration, build tools and runtime data out.
source_roots = ["crates", "apps", "ui", "docs", "scripts", "tests", "packaging", ".github"]
source_files = ["Cargo.toml", "Cargo.lock", "package.json", "package-lock.json", "rustfmt.toml", "README.md", "AGENTS.md", "SECURITY.md", "CONTRIBUTING.md", ".gitignore", "LICENSE", "LICENSE.txt", "NOTICE", "NOTICE.txt", "CHANGELOG.md"]
paths = [root / name for name in source_files]
for folder in source_roots:
    paths.extend((root / folder).rglob("*"))
excluded = {
    "node_modules", "target", "gen", "autogenerated", "__pycache__", "artifacts", "test-results",
    ".git", ".codex", ".agents", ".aws", ".venv", "runtime", "received", "logs", "diagnostic-exports", "local-notes",
}
snapshot = destination / f"Easy-Mouse-Connect-source-{version}-preview.zip"
with zipfile.ZipFile(snapshot, "w", zipfile.ZIP_DEFLATED) as archive:
    for path in sorted(set(paths)):
        relative = path.relative_to(root)
        if not path.is_file() or path.is_symlink() or any(part.lower() in excluded for part in relative.parts):
            continue
        name = path.name.lower()
        if name.startswith(".env") or name == "identity.dat" or name.startswith("identity.dat."):
            continue
        if name.startswith("emc-diagnostics") and path.suffix.lower() == ".zip":
            continue
        if path.suffix.lower() in {".key", ".pem", ".pfx", ".p12", ".dpapi", ".log", ".pyc", ".pdb", ".tmp", ".part"}:
            continue
        archive.write(path, Path("Easy-Mouse-Connect") / relative)
files.append(snapshot.name)
manifest = []
for name in files:
    digest = hashlib.sha256((destination / name).read_bytes()).hexdigest()
    manifest.append(f"{digest}  {name}")
(destination / "SHA256SUMS.txt").write_text("\n".join(manifest) + "\n", encoding="ascii")
for name in files[:3]:
    if hashlib.sha256((package / name).read_bytes()).digest() != hashlib.sha256((destination / name).read_bytes()).digest():
        raise SystemExit(f"Copied file verification failed: {name}")
print(f"Staged and verified {len(files)} files in {destination}")
