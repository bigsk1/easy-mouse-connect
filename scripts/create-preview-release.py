"""Create an unpublished prerelease draft from a verified staged preview.

Run after package-preview.py and stage-preview.py. A trusted manual main CI run
must supply assets built in that same run; checksums alone do not prove a binary
was built from the source. This helper never publishes, replaces or deletes a
release, tag or asset. Requires Python 3.11+, Git and the authenticated gh CLI.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import sys
import tomllib
import zipfile


SOURCE_ROOTS = {"crates", "apps", "ui", "docs", "scripts", "tests", "packaging", ".github"}
SOURCE_FILES = {
    "Cargo.toml", "Cargo.lock", "package.json", "package-lock.json", "rustfmt.toml",
    "README.md", "AGENTS.md", "SECURITY.md", "CONTRIBUTING.md", ".gitignore",
    "LICENSE", "LICENSE.txt", "NOTICE", "NOTICE.txt", "CHANGELOG.md",
}
EXCLUDED_PARTS = {
    "node_modules", "target", "gen", "autogenerated", "__pycache__", "artifacts",
    "test-results", ".git", ".codex", ".agents", ".aws", ".venv", "runtime",
    "received", "logs", "diagnostic-exports", "clipboard-images", "local-notes",
}
EXCLUDED_SUFFIXES = {".key", ".pem", ".pfx", ".p12", ".dpapi", ".log", ".pyc", ".pdb", ".tmp", ".part"}
VERSION_PATTERN = r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def command(arguments, root):
    return subprocess.run(arguments, cwd=root, capture_output=True, text=True,
                          encoding="utf-8", check=False)


def git(root, *arguments):
    result = command(["git", *arguments], root)
    require(result.returncode == 0, "Git verification failed: " + " ".join(arguments))
    return result.stdout


def digest(stream):
    value = hashlib.sha256()
    for block in iter(lambda: stream.read(1024 * 1024), b""):
        value.update(block)
    return value.hexdigest()


def file_digest(path):
    with path.open("rb") as stream:
        return digest(stream)


def checked_checkout(root, expected_head):
    require(Path(git(root, "rev-parse", "--show-toplevel").strip()).resolve() == root,
            "The script must live in the Git repository's scripts directory.")
    head = git(root, "rev-parse", "HEAD").strip()
    require(re.fullmatch(r"(?:[0-9a-f]{40}|[0-9a-f]{64})", expected_head or ""),
            "Supply an exact commit SHA with --expected-head or GITHUB_SHA.")
    require(head == expected_head, "Current HEAD differs from the expected build commit.")
    require(not git(root, "status", "--porcelain=v1", "--untracked-files=no").strip(),
            "Tracked working tree or index is dirty; commit the reviewed source first.")
    tracked = {}
    for record in git(root, "ls-tree", "-r", "--full-tree", "-z", "HEAD").split("\0"):
        if record:
            metadata, name = record.split("\t", 1)
            tracked[name] = metadata.split()[0]
    return head, tracked


def checked_version(root):
    tauri = json.loads((root / "apps/desktop/tauri.conf.json").read_text(encoding="utf-8"))["version"]
    cargo = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))["workspace"]["package"]["version"]
    package = json.loads((root / "package.json").read_text(encoding="utf-8"))["version"]
    lock = json.loads((root / "package-lock.json").read_text(encoding="utf-8"))
    require(isinstance(tauri, str) and re.fullmatch(VERSION_PATTERN, tauri),
            "The preview requires a numeric semver major.minor.patch version.")
    require(all(value == tauri for value in (cargo, package, lock["version"], lock["packages"][""]["version"])),
            "Tauri, Cargo, package.json and package-lock.json versions differ.")
    return tauri


def source_allowed(name):
    path = PurePosixPath(name)
    if name not in SOURCE_FILES and path.parts[0] not in SOURCE_ROOTS:
        return False
    lower = path.name.lower()
    return not (
        any(part.lower() in EXCLUDED_PARTS for part in path.parts)
        or lower.startswith(".env") or lower == "identity.dat" or lower.startswith("identity.dat.")
        or (lower.startswith("emc-diagnostics") and path.suffix.lower() == ".zip")
        or path.suffix.lower() in EXCLUDED_SUFFIXES
    )


def checked_notes(root, notes_file, version, tracked):
    notes = notes_file.resolve(strict=True)
    require(notes.is_relative_to(root), "Release notes must be a tracked Markdown file inside this checkout.")
    name = notes.relative_to(root).as_posix()
    require(tracked.get(name) in {"100644", "100755"} and notes.suffix.lower() == ".md",
            "Release notes must be a tracked regular Markdown file.")
    require(0 < notes.stat().st_size <= 64 * 1024, "Release notes are empty or exceed 64 KiB.")
    text = notes.read_text(encoding="utf-8")
    require("\0" not in text and text.splitlines()[0] == f"# Easy Mouse Connect {version} preview",
            "Release notes heading must match the current preview version.")
    return notes


def checked_source(root, archive_path, tracked):
    expected = {"Easy-Mouse-Connect/" + name: root / name for name, mode in tracked.items()
                if mode in {"100644", "100755"} and source_allowed(name)}
    require(expected, "No tracked source files selected.")
    with zipfile.ZipFile(archive_path) as archive:
        names = archive.namelist()
        require(len(names) == len(set(names)), "Source ZIP contains duplicate names.")
        require(set(names) == set(expected),
                "Source ZIP must contain exactly the sanitized tracked source; missing, private or untracked entries found.")
        for info in archive.infolist():
            path = PurePosixPath(info.filename)
            require(not info.is_dir() and "\\" not in info.filename
                    and not path.is_absolute() and not {".", ".."}.intersection(path.parts)
                    and not stat.S_ISLNK(info.external_attr >> 16) and not info.flag_bits & 1,
                    "Source ZIP contains an unsafe member.")
            source = expected[info.filename]
            require(source.resolve().is_relative_to(root) and not source.is_symlink(),
                    "Source file resolves outside the checkout or is a symlink.")
            require(info.file_size == source.stat().st_size,
                    "Source ZIP bytes differ from the checked checkout: " + info.filename)
            with archive.open(info) as stream:
                require(digest(stream) == file_digest(source),
                        "Source ZIP bytes differ from the checked checkout: " + info.filename)


def checked_assets(root, directory, version, head, repo, tracked):
    directory = directory.resolve(strict=True)
    payloads = {"easy-mouse-connect.exe", f"EasyMouseConnect-{version}-preview-setup.exe",
                "START-HERE.txt", f"Easy-Mouse-Connect-source-{version}-preview.zip"}
    if (directory / "BUILD-INFO.json").exists():
        payloads.add("BUILD-INFO.json")
    require({path.name for path in directory.iterdir()} == payloads | {"SHA256SUMS.txt"},
            "Staged directory must contain only the exact required preview assets (and optional BUILD-INFO.json).")
    for name in payloads | {"SHA256SUMS.txt"}:
        path = directory / name
        require(path.is_file() and not path.is_symlink() and path.stat().st_size > 0,
                "Preview asset is missing, empty, not regular, or a symlink: " + name)
    manifest = directory / "SHA256SUMS.txt"
    require(manifest.stat().st_size <= 16 * 1024, "Checksum manifest exceeds 16 KiB.")
    hashes = {}
    for line in manifest.read_text(encoding="ascii").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  ([A-Za-z0-9_.-]+)", line)
        require(match is not None, "Malformed checksum manifest line.")
        checksum, name = match.groups()
        require(name in payloads and name not in hashes, "Unexpected or duplicate checksum filename.")
        hashes[name] = checksum
    require(set(hashes) == payloads, "Checksum manifest does not cover exactly the preview payloads.")
    for name, checksum in hashes.items():
        require(file_digest(directory / name) == checksum, "Asset checksum mismatch: " + name)
    require((directory / "START-HERE.txt").read_bytes() == (root / "packaging/START-HERE.txt").read_bytes(),
            "Staged instructions differ from this checkout.")
    checked_source(root, directory / f"Easy-Mouse-Connect-source-{version}-preview.zip", tracked)
    if "BUILD-INFO.json" in payloads:
        info_path = directory / "BUILD-INFO.json"
        require(info_path.stat().st_size <= 16 * 1024, "BUILD-INFO exceeds 16 KiB.")
        require(os.environ.get("GITHUB_ACTIONS") == "true", "BUILD-INFO requires a current CI run.")
        expected = {"version": version, "commit": head, "repository": repo,
                    "run_id": os.environ.get("GITHUB_RUN_ID"),
                    "run_attempt": os.environ.get("GITHUB_RUN_ATTEMPT")}
        require(all(expected.values()) and json.loads(info_path.read_text(encoding="utf-8")) == expected,
                "BUILD-INFO does not match this exact CI run, commit and version.")
    return [directory / name for name in sorted(payloads | {"SHA256SUMS.txt"})]


def api(root, endpoint):
    result = command(["gh", "api", "--paginate", "--slurp", endpoint], root)
    require(result.returncode == 0, "GitHub API preflight failed; no release was created.")
    return json.loads(result.stdout)


def checked_github(root, repo, tag, head):
    pages = api(root, f"repos/{repo}/releases?per_page=100")
    require(isinstance(pages, list) and all(isinstance(page, list) for page in pages),
            "Unexpected GitHub release-list response.")
    for page in pages:
        for release in page:
            if release.get("tag_name") == tag:
                state = "draft" if release.get("draft") else "published"
                raise ValueError(f"An existing {state} release uses {tag}; refusing to replace the release or its assets.")
    local = command(["git", "show-ref", "--verify", "--quiet", f"refs/tags/{tag}"], root)
    require(local.returncode in {0, 1}, "Cannot verify the local tag.")
    if local.returncode == 0:
        require(git(root, "rev-parse", f"refs/tags/{tag}^{{commit}}").strip() == head,
                "Existing local tag does not target current HEAD.")
    pages = api(root, f"repos/{repo}/git/matching-refs/tags/{tag}")
    require(isinstance(pages, list) and all(isinstance(page, list) for page in pages),
            "Unexpected GitHub tag-list response.")
    matches = [ref for page in pages for ref in page if ref.get("ref") == f"refs/tags/{tag}"]
    require(len(matches) <= 1, "GitHub returned duplicate matching tags.")
    if matches:
        target = matches[0]["object"]
        for _ in range(8):
            if target["type"] != "tag":
                break
            pages = api(root, f"repos/{repo}/git/tags/{target['sha']}")
            require(len(pages) == 1 and isinstance(pages[0], dict), "Unexpected annotated-tag response.")
            target = pages[0]["object"]
        require(target["type"] == "commit" and target["sha"] == head,
                "Existing remote tag does not target current HEAD.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", required=True, type=Path)
    parser.add_argument("--notes-file", required=True, type=Path)
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--expected-head", default=os.environ.get("GITHUB_SHA"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    require(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", args.repo or ""),
            "Supply an owner/repository with --repo or GITHUB_REPOSITORY.")
    head, tracked = checked_checkout(root, args.expected_head)
    if os.environ.get("GITHUB_ACTIONS") == "true":
        require(os.environ.get("GITHUB_EVENT_NAME") == "workflow_dispatch"
                and os.environ.get("GITHUB_REF") == "refs/heads/main"
                and os.environ.get("GITHUB_REPOSITORY") == args.repo
                and os.environ.get("GITHUB_SHA") == head,
                "CI draft creation requires a manual main run for this repository and exact commit.")
    version = checked_version(root)
    notes = checked_notes(root, args.notes_file, version, tracked)
    assets = checked_assets(root, args.assets, version, head, args.repo, tracked)
    tag = f"v{version}"
    checked_github(root, args.repo, tag, head)
    checked_checkout(root, head)
    result = command(["gh", "release", "create", tag, "--repo", args.repo, "--target", head,
                      "--title", f"Easy Mouse Connect {version} preview", "--notes-file", str(notes),
                      "--draft", "--prerelease", *map(str, assets)], root)
    require(result.returncode == 0,
            "Draft creation/upload failed. An unpublished partial draft may exist; inspect it before retrying. No replacement was attempted.")
    print(f"Created an unpublished prerelease draft for {tag} at {head}.")
    if result.stdout.strip():
        print(result.stdout.strip())
    print("Inspect the draft, assets and acceptance/security evidence before publishing manually.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, TypeError, zipfile.BadZipFile) as error:
        print(f"Preview draft refused: {error}", file=sys.stderr)
        raise SystemExit(1)
